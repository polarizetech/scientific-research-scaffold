"""Find the workbench ({{workbench_repo}}) and its shared tools, or raise with the fix.

Generated by scientific-research-scaffold from the `{{profile}}` profile. See PROTOCOL.md § 4.

The workbench holds tools that have not been released as libraries yet. This file is the only
place this repo looks for it, and it follows three rules:

  1. Resolve, or raise with the line that would resolve it. Never guess a location on someone
     else's filesystem: a default like `~/Sites/<workbench>` works on one machine and fails
     silently everywhere else.
  2. Accept a directory only if it contains the marker file ({{workbench_marker}}). Any folder can
     have the right name; only a real checkout has the marker.
  3. Record which commit was resolved (`provenance()`), so every output says which version of
     the shared code produced it.

Anything produced through here is exploratory. Before a result is quoted outside, release the
tool it used and pin it by tag in pyproject.toml.
"""
from __future__ import annotations

import os
import subprocess
import sys
from pathlib import Path

ENV_VAR = "SCAFFOLD_WORKBENCH"
#: Older variable names, still honoured so existing shells and docs keep working.
ENV_ALIASES: tuple[str, ...] = ({{workbench_aliases}})
MARKER = Path("{{workbench_marker}}")
NAME = "{{workbench_name}}"

#: A sibling checkout: <parent of this repo>/<workbench>. Verified against MARKER before use.
CANDIDATES = (Path(__file__).resolve().parents[2] / NAME,)


class WorkbenchNotFound(RuntimeError):
    """Raised with the exact line that would fix it."""


def root() -> Path:
    """The workbench root, verified by marker."""
    for var in (ENV_VAR, *ENV_ALIASES):
        raw = os.environ.get(var, "").strip()
        if raw:
            p = Path(raw).expanduser().resolve()
            if not (p / MARKER).exists():
                raise WorkbenchNotFound(
                    f"{var} is set to {p}, which has no {MARKER}.\n"
                    f"  That is not a checkout of {NAME}, or it is incomplete."
                )
            return p
    for c in CANDIDATES:
        if (c / MARKER).exists():
            return c.resolve()
    looked = "\n".join(f"      {c}" for c in CANDIDATES)
    raise WorkbenchNotFound(
        f"Could not locate the {NAME} workbench.\n"
        f"  Set it explicitly:\n"
        f"      export {ENV_VAR}=/path/to/{NAME}\n"
        f"  or clone it beside this repo:\n"
        f"      git clone https://github.com/{{workbench_repo}}.git ../{NAME}\n"
        f"  Checked, and rejected for having no {MARKER}:\n{looked}"
    )


def tool(name: str, subdir: str = "tools") -> Path:
    """One named tool's directory, checked."""
    p = root() / subdir / name
    if not p.exists():
        raise WorkbenchNotFound(f"{subdir}/{name} does not exist in {root()}.")
    return p


def add_to_path(*names: str, package_dir: str = "src") -> list[Path]:
    """Put named tools' import roots on sys.path, for local exploration only."""
    added = []
    for name in names:
        p = tool(name) / package_dir if package_dir else tool(name)
        if str(p) not in sys.path:
            sys.path.insert(0, str(p))
        added.append(p)
    return added


def provenance() -> dict:
    """Which workbench commit was resolved. Write this into every output made through it."""
    r = root()
    try:
        commit = subprocess.run(["git", "rev-parse", "HEAD"], cwd=r, capture_output=True,
                                text=True, check=True).stdout.strip()
        dirty = bool(subprocess.run(["git", "status", "--porcelain"], cwd=r, capture_output=True,
                                    text=True, check=True).stdout.strip())
    except (OSError, subprocess.CalledProcessError):
        commit, dirty = None, None
    return {"workbench": "{{workbench_repo}}", "commit": commit, "dirty": dirty}


if __name__ == "__main__":
    import json
    try:
        print(json.dumps({"root": str(root()), **provenance()}, indent=1))
    except WorkbenchNotFound as e:
        sys.exit(str(e))
